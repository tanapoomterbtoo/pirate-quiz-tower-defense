const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const data = {};
for (const subject of ['math', 'science', 'thai', 'pisa', 'exam']) {
    data[subject] = JSON.parse(fs.readFileSync(path.join(root, 'assets/data', subject + '.json')));
    data[subject + 'Scenarios'] = JSON.parse(fs.readFileSync(path.join(root, 'assets/data/scenarios', subject + '.json')));
}
const output = '// Generated by scripts/generate-fallback.cjs. Edit assets/data JSON, then regenerate.\n' +
    '(function(root) { root.FALLBACK_DATA = ' + JSON.stringify(data, null, 2) + '; })(typeof window === "object" ? window : globalThis);\n';
const target = path.join(root, 'web/js/fallback-data.js');
if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) { console.error('Fallback is stale: npm run fallback:generate'); process.exitCode = 1; }
} else fs.writeFileSync(target, output);
